export const cookieErrorKey = (error: unknown): string => {
  const message = error instanceof Error ? error.message : "";
  for (const [code, key] of Object.entries({
    KEYCHAIN_DENIED: "denied",
    UNSUPPORTED_FORMAT: "format",
    INVALID_SELECTION: "selection",
    BUSY: "busy",
    CANCELLED: "cancelled",
    TOO_MANY_COOKIES: "tooMany",
  })) {
    if (message.includes(code)) return key;
  }
  return "error";
};
